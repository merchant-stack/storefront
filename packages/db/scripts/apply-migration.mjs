// One-shot migration applier — bypasses `prisma migrate` because Prisma's Rust
// schema engine can't TLS-handshake with Neon's c-N compute endpoints, while
// node-postgres can. Applies a migration's SQL via pg and records it in
// _prisma_migrations so Prisma considers it applied.
//
// Usage: node scripts/apply-migration.mjs <migration_name>
//   e.g. node scripts/apply-migration.mjs 20260518121357_init

import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import pg from 'pg';

const name = process.argv[2];
if (!name) {
  console.error('Usage: apply-migration.mjs <migration_dir_name>');
  process.exit(1);
}

const url = process.env.DATABASE_URL;
if (!url) {
  console.error('DATABASE_URL is not set');
  process.exit(1);
}

const sqlPath = join('prisma', 'migrations', name, 'migration.sql');
const sql = readFileSync(sqlPath, 'utf8');
const checksum = createHash('sha256').update(sql).digest('hex');

// Split SQL into individual statements. Naive splitter that respects $$-quoted
// strings and string literals — fine for migration DDL generated by Prisma.
function splitStatements(text) {
  const out = [];
  let buf = '';
  let inSingle = false;
  let inDouble = false;
  let inDollar = null;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    const next = text[i + 1];
    if (inDollar) {
      buf += ch;
      if (text.startsWith(inDollar, i)) {
        buf += text.slice(i + 1, i + inDollar.length);
        i += inDollar.length - 1;
        inDollar = null;
      }
      continue;
    }
    if (!inSingle && !inDouble && ch === '$') {
      const m = text.slice(i).match(/^\$[A-Za-z0-9_]*\$/);
      if (m) {
        inDollar = m[0];
        buf += m[0];
        i += m[0].length - 1;
        continue;
      }
    }
    if (!inDouble && ch === "'" && text[i - 1] !== '\\') inSingle = !inSingle;
    if (!inSingle && ch === '"' && text[i - 1] !== '\\') inDouble = !inDouble;
    if (!inSingle && !inDouble && ch === '-' && next === '-') {
      const eol = text.indexOf('\n', i);
      i = eol === -1 ? text.length - 1 : eol;
      continue;
    }
    if (!inSingle && !inDouble && ch === ';') {
      const stmt = buf.trim();
      if (stmt) out.push(stmt);
      buf = '';
      continue;
    }
    buf += ch;
  }
  if (buf.trim()) out.push(buf.trim());
  return out;
}

async function withClient(fn) {
  const c = new pg.Client({ connectionString: url, keepAlive: true });
  c.on('error', () => {});
  await c.connect();
  try {
    return await fn(c);
  } finally {
    try { await c.end(); } catch {}
  }
}

async function runStatement(stmt, attempt = 1) {
  try {
    await withClient((c) => c.query(stmt));
  } catch (e) {
    if (attempt < 3 && /terminated|closed|reset|ECONN/i.test(e.message)) {
      await new Promise((r) => setTimeout(r, 1000 * attempt));
      return runStatement(stmt, attempt + 1);
    }
    throw e;
  }
}

await withClient(async (c) => {
  await c.query(`
    CREATE TABLE IF NOT EXISTS "_prisma_migrations" (
      "id"                    VARCHAR(36) PRIMARY KEY,
      "checksum"              VARCHAR(64) NOT NULL,
      "finished_at"           TIMESTAMPTZ,
      "migration_name"        VARCHAR(255) NOT NULL,
      "logs"                  TEXT,
      "rolled_back_at"        TIMESTAMPTZ,
      "started_at"            TIMESTAMPTZ NOT NULL DEFAULT now(),
      "applied_steps_count"   INTEGER NOT NULL DEFAULT 0
    );
  `);
});

const already = await withClient((c) =>
  c.query('SELECT 1 FROM "_prisma_migrations" WHERE migration_name = $1', [name]),
);
if (already.rowCount > 0) {
  console.log(`Migration ${name} already applied. Skipping.`);
  process.exit(0);
}

const statements = splitStatements(sql);
console.log(`Applying ${name}: ${statements.length} statements`);

for (let i = 0; i < statements.length; i++) {
  process.stdout.write(`  [${i + 1}/${statements.length}] `);
  try {
    await runStatement(statements[i]);
    process.stdout.write('ok\n');
  } catch (e) {
    process.stdout.write('FAIL\n');
    console.error(statements[i].slice(0, 200));
    console.error(e.message);
    process.exit(1);
  }
}

await withClient((c) =>
  c.query(
    `INSERT INTO "_prisma_migrations" (id, checksum, finished_at, migration_name, started_at, applied_steps_count)
     VALUES ($1, $2, now(), $3, now(), $4)`,
    [crypto.randomUUID(), checksum, name, statements.length],
  ),
);
console.log(`Applied ${name} (${statements.length} statements)`);
